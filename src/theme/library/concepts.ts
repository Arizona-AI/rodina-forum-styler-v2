/**
 * Visual concepts — the seed palettes of the built-in catalog.
 *
 * A concept is a hand-tuned, complete `ThemeTokens` set (every color token
 * plus shape/typography fields). Variants are *derived* from these tokens in
 * variants.ts; concept palettes themselves are never computed, so each one
 * keeps a deliberate identity.
 */
import type { ThemeCategory, ThemeMode, ThemeTokens } from "../../types/theme";
import { DEFAULT_FONT_STACK } from "../../types/theme";

/** A base visual idea the catalog is built around. */
export interface ThemeConcept {
  /** Kebab-case slug, unique across concepts. */
  id: string;
  /** Short Russian display name (variants append a suffix to it). */
  name: string;
  /** Russian one-liner describing the mood of the palette. */
  description: string;
  category: ThemeCategory;
  mode: ThemeMode;
  /** Full, standalone token set — every field of `ThemeTokens`. */
  tokens: ThemeTokens;
}

